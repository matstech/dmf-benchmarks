def save_question_result(
    result: dict[str, Any],
    *,
    project_name: str,
    benchmark_name: str = "locomo",
) -> Path:
    """Write one per-question result JSON and return its path."""
    if benchmark_name == "locomo":
        prepare_locomo_strict_evaluation(result)
    question_id = str(result["question_id"])
    output_path = question_result_path(
        project_name=project_name,
        question_id=question_id,
        benchmark_name=benchmark_name,
    )
    output_path.write_text(
        json.dumps(result, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return output_path


def save_question_results(
    results: list[dict[str, Any]],
    *,
    project_name: str,
    benchmark_name: str = "locomo",
) -> list[Path]:
    """Write all per-question results for one batch and return their paths."""
    paths: list[Path] = []
    for result in results:
        paths.append(
            save_question_result(
                result,
                project_name=project_name,
                benchmark_name=benchmark_name,
            )
        )
    return paths


