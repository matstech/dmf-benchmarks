def _extract_longmemeval_strict_session_ids(search_results: list[dict[str, Any]]) -> list[str]:
    seen: set[str] = set()
    session_ids: list[str] = []

    for item in search_results:
        metadata = item.get("metadata")
        if not isinstance(metadata, dict):
            continue

        single_id = metadata.get("source_unit_id") or metadata.get("session_id")
        if isinstance(single_id, str):
            normalized = single_id.strip()
            if normalized and normalized not in seen:
                seen.add(normalized)
                session_ids.append(normalized)

        multiple_ids = metadata.get("source_unit_ids")
        if isinstance(multiple_ids, list):
            for raw_id in multiple_ids:
                if not isinstance(raw_id, str):
                    continue
                normalized = raw_id.strip()
                if normalized and normalized not in seen:
                    seen.add(normalized)
                    session_ids.append(normalized)

    return session_ids


