def load_mem0_question_usage(
    *,
    project_name: str,
    question_id: str,
    benchmark_name: str = "longmemeval",
) -> dict[str, Any]:
    """Load Mem0 internal token accounting for one completed question."""
    input_path = mem0_question_usage_state_path(
        project_name=project_name,
        question_id=question_id,
        benchmark_name=benchmark_name,
    )
    if not input_path.exists():
        raise FileNotFoundError(
            f"Missing Mem0 usage state for question {question_id}: {input_path}"
        )

    payload = json.loads(input_path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"Invalid Mem0 usage state format: {input_path}")

    return normalize_memory_internal_usage(payload.get("memory_internal"))


