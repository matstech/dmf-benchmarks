def build_final_longmemeval_results(
    *,
    project_name: str,
    evaluations: list[dict[str, Any]],
    top_k_cutoffs: list[str] | None = None,
    question_types: list[str] | None = None,
    mode: str = "answerer",
    framework: str | None = None,
    run_metadata: dict[str, Any] | None = None,
    token_accounting: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build the unified LongMemEval result bundle for the rigorous evaluator."""
    strict_evaluations = ensure_longmemeval_strict_evaluations(
        evaluations,
        source_description=(
            f"LongMemEval evaluations for project {project_name}"
        ),
    )

    if top_k_cutoffs is None:
        # Try flat schema first
        for ev in strict_evaluations:
            label = ev.get("cutoff_label")
            if isinstance(label, str) and label.strip():
                top_k_cutoffs = [label.strip()]
                break
        # Fallback to legacy cutoff_results
        if top_k_cutoffs is None:
            for ev in strict_evaluations:
                cr = ev.get("cutoff_results")
                if isinstance(cr, dict) and cr:
                    top_k_cutoffs = sorted(cr.keys())
                    break
        if top_k_cutoffs is None:
            top_k_cutoffs = []

    if question_types is None:
        question_types = sorted(
            {ev.get("question_type", "unknown") for ev in strict_evaluations}
        )

    # Infer framework from evaluations if not explicitly provided
    if framework is None:
        for ev in strict_evaluations:
            fw = ev.get("framework")
            if isinstance(fw, str) and fw:
                framework = fw
                break

    metadata = {
        "benchmark": "longmemeval",
        "mode": mode,
        "project_name": project_name,
        "top_k_cutoffs": top_k_cutoffs,
        "total_questions": len(strict_evaluations),
        "question_types": question_types,
    }
    metadata.update(longmemeval_strict_protocol_metadata())
    if framework:
        metadata["framework"] = framework
    if run_metadata:
        metadata.update(run_metadata)

    return {
        "metadata": metadata,
        "metric_descriptions": dict(METRIC_DESCRIPTIONS),
        "evaluations": strict_evaluations,
        "answerer_usage": aggregate_answerer_usage(strict_evaluations),
        "answerer_usage_by_cutoff": aggregate_usage_by_cutoff(
            strict_evaluations,
            "answerer_usage",
        ),
        "token_accounting": _build_token_accounting_payload(
            evaluations=strict_evaluations,
            token_accounting=token_accounting,
        ),
        "timing_report": build_timing_report(strict_evaluations),
    }


