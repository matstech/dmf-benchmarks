def prepare_longmemeval_strict_evaluation(
    evaluation: dict[str, Any],
) -> dict[str, Any]:
    """Mutate one flat LongMemEval evaluation into the canonical strict artifact shape."""
    if isinstance(evaluation.get("cutoff_results"), dict):
        raise ValueError(
            "LongMemEval strict artifacts require flat mono-cutoff question results. "
            "Legacy cutoff_results artifacts are not supported."
        )
    if "generated_answer" not in evaluation:
        raise ValueError(
            "LongMemEval strict artifacts require flat mono-cutoff question results."
        )

    retrieval = evaluation.get("retrieval")
    if not isinstance(retrieval, dict):
        raise ValueError("LongMemEval strict artifact is missing the retrieval payload.")

    search_results = retrieval.get("search_results")
    if not isinstance(search_results, list):
        raise ValueError("LongMemEval strict artifact is missing retrieval.search_results.")

    strict_context = str(
        retrieval.get("strict_context")
        or retrieval.get("context")
        or ""
    ).strip()
    if not strict_context:
        raise ValueError("LongMemEval strict artifact is missing retrieval.strict_context/context.")

    strict_session_ids = _normalize_longmemeval_strict_session_ids(
        retrieval.get("strict_session_ids")
    )
    if not strict_session_ids:
        strict_session_ids = _extract_longmemeval_strict_session_ids(search_results)

    retrieval["strict_context"] = strict_context
    retrieval["strict_session_ids"] = strict_session_ids
    retrieval["context"] = strict_context
    evaluation.update(longmemeval_strict_protocol_metadata())
    return evaluation


def ensure_longmemeval_strict_evaluation(
    evaluation: dict[str, Any],
    *,
    source_description: str,
) -> dict[str, Any]:
    """Validate that one LongMemEval artifact is already in canonical strict form."""
    if isinstance(evaluation.get("cutoff_results"), dict):
        raise ValueError(
            f"{source_description} is not a LongMemEval strict flat artifact "
            "(found legacy cutoff_results schema)."
        )
    if "generated_answer" not in evaluation:
        raise ValueError(
            f"{source_description} is not a LongMemEval strict flat artifact."
        )

    expected_protocol = longmemeval_strict_protocol_metadata()
    for key, expected_value in expected_protocol.items():
        actual_value = str(evaluation.get(key, "") or "").strip()
        if actual_value != expected_value:
            raise ValueError(
                f"{source_description} is not a LongMemEval strict artifact: "
                f"missing or incompatible {key!r}."
            )

    retrieval = evaluation.get("retrieval")
    if not isinstance(retrieval, dict):
        raise ValueError(f"{source_description} is missing a retrieval payload.")

    search_results = retrieval.get("search_results")
    if not isinstance(search_results, list):
        raise ValueError(f"{source_description} is missing retrieval.search_results.")

    strict_context = retrieval.get("strict_context")
    if not isinstance(strict_context, str) or not strict_context.strip():
        raise ValueError(f"{source_description} is missing retrieval.strict_context.")

    if str(retrieval.get("context", "") or "").strip() != strict_context.strip():
        raise ValueError(
            f"{source_description} is incompatible with LongMemEval strict: "
            "retrieval.context does not match retrieval.strict_context."
        )

    strict_session_ids = retrieval.get("strict_session_ids")
    if not isinstance(strict_session_ids, list):
        raise ValueError(f"{source_description} is missing retrieval.strict_session_ids.")

    normalized_session_ids = _normalize_longmemeval_strict_session_ids(strict_session_ids)
    if strict_context.strip() != LONGMEMEVAL_NO_HISTORY_CHATS and not normalized_session_ids:
        raise ValueError(
            f"{source_description} is missing mappable retrieval.strict_session_ids for "
            "a non-empty strict context."
        )

    return evaluation


def ensure_longmemeval_strict_evaluations(
    evaluations: list[dict[str, Any]],
    *,
    source_description: str,
) -> list[dict[str, Any]]:
    """Validate a list of LongMemEval per-question artifacts as strict-compatible."""
