def _load_and_validate_locomo_marker(
    path: Path,
) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"Invalid LoCoMo marker payload: {path}")

    expected_protocol = locomo_strict_protocol_metadata()
    for key, expected_value in expected_protocol.items():
        actual_value = str(payload.get(key, "") or "").strip()
        if actual_value != expected_value:
            raise ValueError(
                f"Incompatible LoCoMo marker {path.name}: expected strict {key}="
                f"{expected_value!r}, found {actual_value!r}."
            )
    return payload


def ensure_locomo_uniform_schema(evaluations: list[dict[str, Any]]) -> str:
    """Ensure all LOCOMO evaluations share one supported result schema."""
    schemas = {locomo_result_schema(evaluation) for evaluation in evaluations}
    known_schemas = schemas - {"unknown"}

    if "unknown" in schemas:
        raise ValueError(
            "Unsupported LOCOMO evaluation payload: expected flat mono-cutoff "
            "items or legacy cutoff_results items."
        )

    if len(known_schemas) > 1:
        raise ValueError(
            "Mixed LOCOMO result schemas detected in one run output. "
            "Found both flat mono-cutoff items and legacy cutoff_results items."
        )

    return next(iter(known_schemas), "flat")


def _iter_usage_entries(
    evaluation: dict[str, Any],
    usage_key: str,
) -> list[tuple[str | None, dict[str, int]]]:
    cutoff_results = evaluation.get("cutoff_results")
    if isinstance(cutoff_results, dict):
        entries: list[tuple[str | None, dict[str, int]]] = []
        for cutoff_label, cutoff in cutoff_results.items():
            if not isinstance(cutoff, dict):
                continue

            usage = cutoff.get(usage_key)
            if not isinstance(usage, dict):
                continue
            entries.append((str(cutoff_label), normalize_answerer_usage(usage)))
        return entries

    usage = evaluation.get(usage_key)
    if not isinstance(usage, dict):
        return []

    return [(_flat_cutoff_label(evaluation), normalize_answerer_usage(usage))]


def aggregate_answerer_usage(evaluations: list[dict[str, Any]]) -> dict[str, int]:
    """Aggregate answerer usage across flat or cutoff-nested evaluations."""
    total = empty_answerer_usage()
    for evaluation in evaluations:
        for _, usage in _iter_usage_entries(evaluation, "answerer_usage"):
            total = add_answerer_usage(total, usage)
    return total


def aggregate_usage_by_cutoff(
    evaluations: list[dict[str, Any]],
    usage_key: str,
) -> dict[str, dict[str, int]]:
    """Aggregate one usage field separately for each cutoff label."""
    totals: dict[str, dict[str, int]] = {}

    for evaluation in evaluations:
        for cutoff_label, usage in _iter_usage_entries(evaluation, usage_key):
            if not cutoff_label:
                continue
            bucket = totals.setdefault(cutoff_label, empty_answerer_usage())
            totals[cutoff_label] = add_answerer_usage(bucket, usage)

    return totals


def _build_token_accounting_payload(
    *,
    evaluations: list[dict[str, Any]],
    token_accounting: dict[str, Any] | None,
) -> dict[str, Any]:
    """Return unified token accounting with explicit answerer and memory buckets."""
    answerer_usage = aggregate_answerer_usage(evaluations)
    payload = dict(token_accounting or {})
    payload.setdefault(
        "memory_internal",
        empty_memory_internal_usage(framework=None),
    )
    payload.setdefault("answerer", answerer_usage)
    return payload


