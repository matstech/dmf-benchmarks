def empty_answerer_usage() -> dict[str, int]:
    """Return the normalized zero usage structure for answer generation."""
    return {
        "prompt_tokens_total": 0,
        "completion_tokens": 0,
        "total_tokens": 0,
    }


def normalize_answerer_usage(data: dict[str, Any] | None) -> dict[str, int]:
    """Normalize one answerer usage payload to the canonical integer shape."""
    usage = empty_answerer_usage()
    if not isinstance(data, dict):
        return usage

    usage["prompt_tokens_total"] = int(data.get("prompt_tokens_total", 0) or 0)
    usage["completion_tokens"] = int(data.get("completion_tokens", 0) or 0)
    usage["total_tokens"] = int(data.get("total_tokens", 0) or 0)
    return usage


def add_answerer_usage(*usages: dict[str, Any] | None) -> dict[str, int]:
    """Sum multiple normalized or partially-normalized answerer usages."""
    total = empty_answerer_usage()
    for usage in usages:
        normalized = normalize_answerer_usage(usage)
        for key in total:
            total[key] += normalized[key]
    return total


def normalize_pipeline_timing(data: dict[str, Any] | None) -> dict[str, Any]:
    """Normalize per-item pipeline timing fields to canonical float/scope pairs."""
    if not isinstance(data, dict):
        return {}

    normalized: dict[str, Any] = {}
    for value_key, scope_key in PIPELINE_TIMING_FIELDS.values():
        raw_value = data.get(value_key)
        if raw_value is None:
            continue
        normalized[value_key] = max(float(raw_value or 0.0), 0.0)
        raw_scope = str(data.get(scope_key, TIMING_SCOPE_QUESTION) or TIMING_SCOPE_QUESTION)
        scope = raw_scope.strip().lower()
        if scope not in {TIMING_SCOPE_QUESTION, TIMING_SCOPE_CONVERSATION}:
            scope = TIMING_SCOPE_QUESTION
        normalized[scope_key] = scope
    return normalized


def _timing_identity(evaluation: dict[str, Any], *, scope: str, fallback_index: int) -> str:
    if scope == TIMING_SCOPE_CONVERSATION:
        conversation_idx = evaluation.get("conversation_idx")
        if conversation_idx is not None:
            return f"conversation:{conversation_idx}"
    question_id = evaluation.get("question_id")
    if question_id is not None:
        return f"question:{question_id}"
    return f"index:{fallback_index}"


def build_timing_report(evaluations: list[dict[str, Any]]) -> dict[str, Any]:
    """Aggregate per-item pipeline timing into final per-stage summaries."""
    report: dict[str, Any] = {}

    for stage_name, (value_key, scope_key) in PIPELINE_TIMING_FIELDS.items():
        stage_values: dict[str, float] = {}
        stage_scope: str | None = None

        for index, evaluation in enumerate(evaluations):
            timing = normalize_pipeline_timing(evaluation.get("pipeline_timing"))
            if value_key not in timing:
                continue
            scope = str(timing.get(scope_key, TIMING_SCOPE_QUESTION))
            stage_scope = scope
            identity = _timing_identity(
                evaluation,
                scope=scope,
                fallback_index=index,
            )
            stage_values[identity] = float(timing[value_key])

        if not stage_values:
            continue

        values = list(stage_values.values())
        report[stage_name] = {
            "scope": stage_scope or TIMING_SCOPE_QUESTION,
            "count": len(values),
            "total_ms": sum(values),
            "avg_ms": mean(values),
            "min_ms": min(values),
            "max_ms": max(values),
        }

    return report


def normalize_native_resource_stage(data: dict[str, Any] | None) -> dict[str, Any]:
    """Normalize one native resource usage stage summary."""
    if not isinstance(data, dict):
        return {}

    scope = str(data.get("scope", TIMING_SCOPE_QUESTION) or TIMING_SCOPE_QUESTION)
    normalized = {
        "scope": (
            scope.strip().lower()
            if scope.strip().lower()
            in {TIMING_SCOPE_QUESTION, TIMING_SCOPE_CONVERSATION}
            else TIMING_SCOPE_QUESTION
        )
    }
    for field in NATIVE_RESOURCE_NUMERIC_FIELDS:
        normalized[field] = max(float(data.get(field, 0.0) or 0.0), 0.0)
    return normalized


def normalize_native_resource_usage(data: dict[str, Any] | None) -> dict[str, Any]:
    """Normalize nested native resource usage by stage."""
    if not isinstance(data, dict):
        return {}

    normalized: dict[str, Any] = {}
    for stage in NATIVE_RESOURCE_STAGES:
        stage_data = normalize_native_resource_stage(data.get(stage))
        if stage_data:
            normalized[stage] = stage_data
    return normalized


def build_native_resource_report(evaluations: list[dict[str, Any]]) -> dict[str, Any]:
    """Aggregate native per-item resource usage into stage summaries."""
    report: dict[str, Any] = {}

    for stage in NATIVE_RESOURCE_STAGES:
        stage_values: dict[str, dict[str, Any]] = {}
        stage_scope: str | None = None

        for index, evaluation in enumerate(evaluations):
            resource_usage = normalize_native_resource_usage(
                evaluation.get("resource_usage")
            )
            if stage not in resource_usage:
                continue
            stage_entry = resource_usage[stage]
            stage_scope = str(stage_entry.get("scope", TIMING_SCOPE_QUESTION))
            identity = _timing_identity(
                evaluation,
                scope=stage_scope,
                fallback_index=index,
            )
            stage_values[identity] = stage_entry

        if not stage_values:
            continue

        values = list(stage_values.values())
        report[stage] = {
            "scope": stage_scope or TIMING_SCOPE_QUESTION,
            "count": len(values),
            "avg_rss_start_mb": round(mean(item["rss_start_mb"] for item in values), 2),
            "avg_rss_end_mb": round(mean(item["rss_end_mb"] for item in values), 2),
            "avg_rss_peak_mb": round(mean(item["rss_peak_mb"] for item in values), 2),
            "max_rss_peak_mb": round(max(item["rss_peak_mb"] for item in values), 2),
            "total_cpu_user_s": round(sum(item["cpu_user_s"] for item in values), 4),
            "total_cpu_system_s": round(sum(item["cpu_system_s"] for item in values), 4),
            "avg_cpu_percent": round(mean(item["cpu_percent_avg"] for item in values), 2),
        }

    return report


