def load_question_results(
    *,
    project_name: str,
    benchmark_name: str = "locomo",
) -> list[dict[str, Any]]:
    """Load all per-question result JSON files for one project run."""
    output_dir = predicted_results_dir(
        project_name=project_name,
        benchmark_name=benchmark_name,
    )
    if not output_dir.exists():
        return []

    results: list[dict[str, Any]] = []
    for path in sorted(output_dir.glob("*.json")):
        if path.name.startswith("_"):
            continue
        results.append(json.loads(path.read_text(encoding="utf-8")))
    return results


def load_question_results_for_ids(
    *,
    project_name: str,
    question_ids: list[str],
    benchmark_name: str = "longmemeval",
) -> list[dict[str, Any]]:
    """Load per-question result JSON files in the requested question order."""
    results: list[dict[str, Any]] = []
    for question_id in question_ids:
        path = question_result_path(
            project_name=project_name,
            question_id=question_id,
            benchmark_name=benchmark_name,
        )
        if not path.exists():
            continue
        results.append(json.loads(path.read_text(encoding="utf-8")))
    return results


