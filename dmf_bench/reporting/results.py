def empty_answerer_usage() -> dict[str, int]:
    """Return the normalized zero usage structure for answer generation."""
    return {
        "prompt_tokens_total": 0,
        "completion_tokens": 0,
        "total_tokens": 0,
    }


def normalize_answerer_usage(data: dict[str, Any] | None) -> dict[str, int]:
    """Normalize one answerer usage payload to the canonical integer shape."""
    usage = empty_answerer_usage()
    if not isinstance(data, dict):
        return usage

    usage["prompt_tokens_total"] = int(data.get("prompt_tokens_total", 0) or 0)
    usage["completion_tokens"] = int(data.get("completion_tokens", 0) or 0)
    usage["total_tokens"] = int(data.get("total_tokens", 0) or 0)
    return usage


def add_answerer_usage(*usages: dict[str, Any] | None) -> dict[str, int]:
    """Sum multiple normalized or partially-normalized answerer usages."""
    total = empty_answerer_usage()
    for usage in usages:
        normalized = normalize_answerer_usage(usage)
        for key in total:
            total[key] += normalized[key]
    return total


def normalize_pipeline_timing(data: dict[str, Any] | None) -> dict[str, Any]:
    """Normalize per-item pipeline timing fields to canonical float/scope pairs."""
    if not isinstance(data, dict):
        return {}

    normalized: dict[str, Any] = {}
    for value_key, scope_key in PIPELINE_TIMING_FIELDS.values():
        raw_value = data.get(value_key)
        if raw_value is None:
            continue
        normalized[value_key] = max(float(raw_value or 0.0), 0.0)
        raw_scope = str(data.get(scope_key, TIMING_SCOPE_QUESTION) or TIMING_SCOPE_QUESTION)
        scope = raw_scope.strip().lower()
        if scope not in {TIMING_SCOPE_QUESTION, TIMING_SCOPE_CONVERSATION}:
            scope = TIMING_SCOPE_QUESTION
        normalized[scope_key] = scope
    return normalized


def _timing_identity(evaluation: dict[str, Any], *, scope: str, fallback_index: int) -> str:
    if scope == TIMING_SCOPE_CONVERSATION:
        conversation_idx = evaluation.get("conversation_idx")
        if conversation_idx is not None:
            return f"conversation:{conversation_idx}"
    question_id = evaluation.get("question_id")
    if question_id is not None:
        return f"question:{question_id}"
    return f"index:{fallback_index}"


def build_timing_report(evaluations: list[dict[str, Any]]) -> dict[str, Any]:
    """Aggregate per-item pipeline timing into final per-stage summaries."""
    report: dict[str, Any] = {}

    for stage_name, (value_key, scope_key) in PIPELINE_TIMING_FIELDS.items():
        stage_values: dict[str, float] = {}
        stage_scope: str | None = None

        for index, evaluation in enumerate(evaluations):
            timing = normalize_pipeline_timing(evaluation.get("pipeline_timing"))
            if value_key not in timing:
                continue
            scope = str(timing.get(scope_key, TIMING_SCOPE_QUESTION))
            stage_scope = scope
            identity = _timing_identity(
                evaluation,
                scope=scope,
                fallback_index=index,
            )
            stage_values[identity] = float(timing[value_key])

        if not stage_values:
            continue

        values = list(stage_values.values())
        report[stage_name] = {
            "scope": stage_scope or TIMING_SCOPE_QUESTION,
            "count": len(values),
            "total_ms": sum(values),
            "avg_ms": mean(values),
            "min_ms": min(values),
            "max_ms": max(values),
        }

    return report


def normalize_native_resource_stage(data: dict[str, Any] | None) -> dict[str, Any]:
    """Normalize one native resource usage stage summary."""
    if not isinstance(data, dict):
        return {}

    scope = str(data.get("scope", TIMING_SCOPE_QUESTION) or TIMING_SCOPE_QUESTION)
    normalized = {
        "scope": (
            scope.strip().lower()
            if scope.strip().lower()
            in {TIMING_SCOPE_QUESTION, TIMING_SCOPE_CONVERSATION}
            else TIMING_SCOPE_QUESTION
        )
    }
    for field in NATIVE_RESOURCE_NUMERIC_FIELDS:
        normalized[field] = max(float(data.get(field, 0.0) or 0.0), 0.0)
    return normalized


def normalize_native_resource_usage(data: dict[str, Any] | None) -> dict[str, Any]:
    """Normalize nested native resource usage by stage."""
    if not isinstance(data, dict):
        return {}

    normalized: dict[str, Any] = {}
    for stage in NATIVE_RESOURCE_STAGES:
        stage_data = normalize_native_resource_stage(data.get(stage))
        if stage_data:
            normalized[stage] = stage_data
    return normalized


def build_native_resource_report(evaluations: list[dict[str, Any]]) -> dict[str, Any]:
    """Aggregate native per-item resource usage into stage summaries."""
    report: dict[str, Any] = {}

    for stage in NATIVE_RESOURCE_STAGES:
        stage_values: dict[str, dict[str, Any]] = {}
        stage_scope: str | None = None

        for index, evaluation in enumerate(evaluations):
            resource_usage = normalize_native_resource_usage(
                evaluation.get("resource_usage")
            )
            if stage not in resource_usage:
                continue
            stage_entry = resource_usage[stage]
            stage_scope = str(stage_entry.get("scope", TIMING_SCOPE_QUESTION))
            identity = _timing_identity(
                evaluation,
                scope=stage_scope,
                fallback_index=index,
            )
            stage_values[identity] = stage_entry

        if not stage_values:
            continue

        values = list(stage_values.values())
        report[stage] = {
            "scope": stage_scope or TIMING_SCOPE_QUESTION,
            "count": len(values),
            "avg_rss_start_mb": round(mean(item["rss_start_mb"] for item in values), 2),
            "avg_rss_end_mb": round(mean(item["rss_end_mb"] for item in values), 2),
            "avg_rss_peak_mb": round(mean(item["rss_peak_mb"] for item in values), 2),
            "max_rss_peak_mb": round(max(item["rss_peak_mb"] for item in values), 2),
            "total_cpu_user_s": round(sum(item["cpu_user_s"] for item in values), 4),
            "total_cpu_system_s": round(sum(item["cpu_system_s"] for item in values), 4),
            "avg_cpu_percent": round(mean(item["cpu_percent_avg"] for item in values), 2),
        }

    return report


def empty_native_latency_breakdown() -> dict[str, float]:
    """Return the canonical native latency accounting shape in milliseconds."""
    return {
        "framework_retrieval_ms": 0.0,
        "answerer_ms": 0.0,
        "total_end_to_end_ms": 0.0,
    }


def normalize_native_latency_breakdown(
    data: dict[str, Any] | None,
) -> dict[str, float]:
    """Normalize native framework, answerer, and total latency values."""
    latency = empty_native_latency_breakdown()
    if not isinstance(data, dict):
        return latency

    for key in latency:
        latency[key] = float(data.get(key, 0.0) or 0.0)
    if latency["total_end_to_end_ms"] <= 0.0:
        latency["total_end_to_end_ms"] = (
            latency["framework_retrieval_ms"] + latency["answerer_ms"]
        )
    return latency


def normalize_native_memory_internal_usage(
    data: dict[str, Any] | None,
    *,
    framework: str | None = None,
    diagnostics: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Normalize internal memory usage while preserving non-token diagnostics.

    Provider token fields are populated only when observed. Framework-native
    diagnostics are retained separately so they do not inflate token totals.
    """
    usage = normalize_memory_internal_usage(data)
    if framework is not None and usage.get("framework") is None:
        usage["framework"] = framework
    if diagnostics:
        usage["observed_diagnostics"] = dict(diagnostics)
    return usage


def total_native_end_to_end_tokens(
    *,
    answerer_usage: dict[str, Any] | None,
    memory_internal_usage: dict[str, Any] | None,
) -> int:
    """Return observed native end-to-end tokens.

    If the memory framework does not expose internal provider token usage, the
    total is equal to the answerer total.
    """
    answerer = normalize_answerer_usage(answerer_usage)
    memory = normalize_memory_internal_usage(memory_internal_usage)
    return int(answerer["total_tokens"] + memory["total_tokens"])


def native_retrieval_search_results(raw_retrieval_outputs: Any) -> list[Any]:
    """Return a flat search_results view for secondary offline evaluators."""
    if isinstance(raw_retrieval_outputs, dict):
        for key in ("search_results", "results", "final_candidates"):
            value = raw_retrieval_outputs.get(key)
            if isinstance(value, list):
                return list(value)

    if isinstance(raw_retrieval_outputs, list):
        return list(raw_retrieval_outputs)
    return []


def build_native_evaluation_item(
    *,
    base_result: dict[str, Any],
    native_context: Any,
    task_prompt: str,
    surface_marker: str,
    raw_retrieval_outputs: Any,
    answerer_usage: dict[str, Any] | None,
    memory_internal_usage: dict[str, Any] | None = None,
    latency_breakdown: dict[str, Any] | None = None,
    memory_diagnostics: dict[str, Any] | None = None,
    pipeline_timing: dict[str, Any] | None = None,
    resource_usage: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Return one canonical native item with evaluator-compatible flat fields."""
    normalized_answerer = normalize_answerer_usage(answerer_usage)
    normalized_memory = normalize_native_memory_internal_usage(
        memory_internal_usage,
        framework=str(base_result.get("framework") or "") or None,
        diagnostics=memory_diagnostics,
    )
    normalized_latency = normalize_native_latency_breakdown(latency_breakdown)
    normalized_pipeline_timing = normalize_pipeline_timing(pipeline_timing)
    normalized_resource_usage = normalize_native_resource_usage(resource_usage)
    if "qa_ms" not in normalized_pipeline_timing and normalized_latency["total_end_to_end_ms"] > 0.0:
        normalized_pipeline_timing["qa_ms"] = normalized_latency["total_end_to_end_ms"]
        normalized_pipeline_timing["qa_scope"] = TIMING_SCOPE_QUESTION
    search_results = native_retrieval_search_results(raw_retrieval_outputs)

    retrieval = dict(base_result.get("retrieval") or {})
    retrieval.setdefault("search_results", search_results)
    retrieval.setdefault("memories_evaluated", len(search_results))
    retrieval.setdefault("native_context", native_context)
    retrieval.setdefault("surface_marker", surface_marker)
    retrieval.setdefault(
        "retrieval_pipeline_latency_ms",
        normalized_latency["framework_retrieval_ms"],
    )
    retrieval.setdefault(
        "search_latency_ms",
        normalized_latency["framework_retrieval_ms"],
    )

    item = dict(base_result)
    item.update(
        {
            "surface_marker": surface_marker,
            "native_context": native_context,
            "task_prompt": task_prompt,
            "raw_retrieval_outputs": raw_retrieval_outputs,
            "answerer_usage": normalized_answerer,
            "memory_internal_usage": normalized_memory,
            "total_end_to_end_tokens": total_native_end_to_end_tokens(
                answerer_usage=normalized_answerer,
                memory_internal_usage=normalized_memory,
            ),
            "latency_breakdown": normalized_latency,
            "retrieval": retrieval,
        }
    )
    if normalized_pipeline_timing:
        item["pipeline_timing"] = normalized_pipeline_timing
    if normalized_resource_usage:
        item["resource_usage"] = normalized_resource_usage
    item.setdefault("judge_score", None)
    return item


def aggregate_native_token_totals(evaluations: list[dict[str, Any]]) -> dict[str, Any]:
    """Aggregate native answerer, memory, and observed end-to-end token totals."""
    answerer = aggregate_answerer_usage(evaluations)
    memory_total = empty_memory_internal_usage(framework=None)
    total_end_to_end_tokens = 0

    for evaluation in evaluations:
        memory = normalize_memory_internal_usage(
            evaluation.get("memory_internal_usage")
        )
        if memory_total["framework"] is None and memory.get("framework") is not None:
            memory_total["framework"] = memory["framework"]
        memory_total["available"] = memory_total["available"] or memory["available"]
        memory_total["prompt_tokens"] += memory["prompt_tokens"]
        memory_total["completion_tokens"] += memory["completion_tokens"]
        memory_total["total_tokens"] += memory["total_tokens"]
        memory_total["calls"] += memory["calls"]
        total_end_to_end_tokens += int(
            evaluation.get("total_end_to_end_tokens")
            or total_native_end_to_end_tokens(
                answerer_usage=evaluation.get("answerer_usage"),
                memory_internal_usage=memory,
            )
        )

    return {
        "answerer": answerer,
        "memory_internal": memory_total,
        "total_end_to_end_tokens": total_end_to_end_tokens,
        "note": (
            "Memory internal provider tokens are included only when exposed by "
            "the framework surface; otherwise totals reflect observed answerer tokens."
        ),
    }


def aggregate_native_latency_breakdown(
    evaluations: list[dict[str, Any]],
) -> dict[str, float]:
    """Aggregate native latency breakdown totals across evaluations."""
    totals = empty_native_latency_breakdown()
    for evaluation in evaluations:
        latency = normalize_native_latency_breakdown(
            evaluation.get("latency_breakdown")
        )
        for key in totals:
            totals[key] += latency[key]
    return totals


def build_native_results_bundle(
    *,
    project_name: str,
    benchmark_name: str,
    evaluations: list[dict[str, Any]],
    framework: str | None = None,
    run_metadata: dict[str, Any] | None = None,
    results_path: str | Path | None = None,
) -> dict[str, Any]:
    """Build a native flat bundle consumable by secondary offline evaluators."""
    metadata = {
        "benchmark": benchmark_name,
        "project_name": project_name,
        "total_questions": len(evaluations),
    }
    if framework:
        metadata["framework"] = framework
    if run_metadata:
        metadata.update(run_metadata)

    bundle = {
        "metadata": metadata,
        "metric_descriptions": dict(METRIC_DESCRIPTIONS),
        "evaluations": evaluations,
        "primary_quality": aggregate_native_primary_quality(
            evaluations,
            benchmark_name=benchmark_name,
        ),
        "answerer_usage": aggregate_answerer_usage(evaluations),
        "token_accounting": aggregate_native_token_totals(evaluations),
        "latency_breakdown": aggregate_native_latency_breakdown(evaluations),
        "timing_report": build_timing_report(evaluations),
        "resource_report": build_native_resource_report(evaluations),
    }
    if results_path is not None:
        bundle["primary_quality_report"] = build_native_primary_quality_report(
            bundle=bundle,
            input_path=results_path,
        )
        bundle["secondary_rigorous"] = build_native_secondary_rigorous_manifest(
            benchmark_name=benchmark_name,
            input_path=results_path,
            project_name=project_name,
        )
    return bundle


def _flat_cutoff_label(evaluation: dict[str, Any]) -> str | None:
    raw_label = evaluation.get("cutoff_label")
    if not isinstance(raw_label, str):
        return None

    label = raw_label.strip()
    return label or None


def _iter_usage_entries(
    evaluation: dict[str, Any],
    usage_key: str,
) -> list[tuple[str | None, dict[str, int]]]:
    cutoff_results = evaluation.get("cutoff_results")
    if isinstance(cutoff_results, dict):
        entries: list[tuple[str | None, dict[str, int]]] = []
        for cutoff_label, cutoff in cutoff_results.items():
            if not isinstance(cutoff, dict):
                continue

            usage = cutoff.get(usage_key)
            if not isinstance(usage, dict):
                continue
            entries.append((str(cutoff_label), normalize_answerer_usage(usage)))
        return entries

    usage = evaluation.get(usage_key)
    if not isinstance(usage, dict):
        return []

    return [(_flat_cutoff_label(evaluation), normalize_answerer_usage(usage))]


def aggregate_answerer_usage(evaluations: list[dict[str, Any]]) -> dict[str, int]:
    """Aggregate answerer usage across flat or cutoff-nested evaluations."""
    total = empty_answerer_usage()
    for evaluation in evaluations:
        for _, usage in _iter_usage_entries(evaluation, "answerer_usage"):
            total = add_answerer_usage(total, usage)
    return total
